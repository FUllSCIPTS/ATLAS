"""Export ATLAS Go 1.4's LSTM weights and a recorded run of its live loop for the explorer's ML labs.

Writes architecture-explorer/dist/ml-live.js with two constants:
  ML_LSTM  the on-device LSTM (android-app/atlas_go/lstm_weights.py: W, B, V, C, the reference window
           REF_X and its forecast REF_Y), so the browser can run the same forward pass as loop.lstm_hidden
           and loop.head and check that it gives the same forecast;
  ML_LOOP  a recorded run of loop.Loop over the Cork Jazz weekend 2026 (9 city days): every hour's demand,
           the LSTM forecast, the agent's boost and the cost, the 1.2 calendar agent's and no-boost costs on
           the same demand, and each night's champion/challenger validation report.

Usage: python architecture-explorer/starter/scripts/export_ml_live.py --main <checkout of main>
"""

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "dist/ml-live.js"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--main", required=True, help="checkout of the main branch")
    args = parser.parse_args()
    sys.path.insert(0, str(Path(args.main) / "android-app"))
    from atlas_go import learned, loop as live, lstm_weights as LW

    start, days = dt.datetime(2026, 10, 19), 9
    lp = live.Loop()
    lp.warm_up(live.hour_index(start))
    rows = []
    for _ in range(days * 24):
        r = lp.step()
        t = live.hour_time(r["i"])
        g = live.tag(t)
        cal = learned.BOOST.get(f"{g}|{live.weektype(t) if g == 'ordinary' else 0}|{t.hour}", 0.0)
        sup = r["ty"] * 1.03
        rows.append([r["d"], r["ty"], r["f"], r["boost"], r["cost"], round(live._cost(r["d"], sup, cal)[2], 2),
                     cal, round(live._cost(r["d"], sup, 0.0)[2], 2), r["lv"], g])
    lstm = dict(W=LW.W, B=LW.B, V=LW.V, C=LW.C, REF_X=LW.REF_X, REF_Y=LW.REF_Y, TAGS=LW.TAGS, BOOSTS=LW.BOOSTS,
                BUCKETS=list(LW.BUCKETS), METRICS=LW.METRICS, L_IN=LW.L_IN, NH=LW.NH, HZ=LW.HZ,
                version=LW.LSTM_VERSION)
    trace = dict(period="Cork Jazz weekend 2026", start=start.isoformat(), rows=rows, updates=lp.state["updates"],
                 lstm_version=lp.state["lstm"]["n"], agent_version=lp.state["agent"]["n"])
    text = ("// Generated by starter/scripts/export_ml_live.py from main: android-app/atlas_go/lstm_weights.py and a\n"
            "// recorded run of android-app/atlas_go/loop.py (ATLAS Go 1.4.0). Do not edit by hand.\n"
            "// ML_LOOP.rows: [demand, ordinary demand, LSTM forecast (6 h, ÷ ordinary), boost, cost,\n"
            "//                calendar-agent cost, calendar boost, no-boost cost, forecast level, calendar tag]\n"
            f"const ML_LSTM = {json.dumps(lstm, separators=(',', ':'))};\n"
            f"const ML_LOOP = {json.dumps(trace, separators=(',', ':'))};\n")
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text) // 1024} KB, {len(rows)} hours, {len(trace['updates'])} nightly updates)")


if __name__ == "__main__":
    main()
